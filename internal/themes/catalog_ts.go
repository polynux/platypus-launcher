package themes

import (
	"fmt"
	"strings"
)

// CatalogTS renders the catalog's variant axes for the UI
// (apps/ui/src/gen/catalog.ts, written by `go run ./cmd/gen-ts`): the axis
// names, the values each one takes and its built-in value. The UI reads
// variants by these names, so a renamed axis fails its typecheck.
func CatalogTS() string {
	var b strings.Builder
	b.WriteString("// Generated by `go run ./cmd/gen-ts` from internal/themes/catalog.go. Do not edit.\n\n")
	b.WriteString("/** The values each catalog variant axis takes, by \"entry.axis\". */\n")
	b.WriteString("export interface VariantValues {\n")
	var defaults strings.Builder
	for _, entry := range Catalog {
		for _, axis := range entry.Axes {
			key := entry.Entry + "." + axis.Name
			values := make([]string, len(axis.Values))
			for i, v := range axis.Values {
				values[i] = fmt.Sprintf("%q", v)
			}
			fmt.Fprintf(&b, "  %q: %s;\n", key, strings.Join(values, " | "))
			fmt.Fprintf(&defaults, "  %q: %q,\n", key, axis.Default)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("export type VariantAxis = keyof VariantValues;\n\n")
	b.WriteString("/** Each axis's built-in value: what the app shows with no theme. */\n")
	b.WriteString("export const VARIANT_DEFAULTS: VariantValues = {\n")
	b.WriteString(defaults.String())
	b.WriteString("};\n")
	return b.String()
}
