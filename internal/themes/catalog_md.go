package themes

import (
	"fmt"
	"strings"

	"platypus/internal/types"
)

// CatalogMD renders the catalog reference (docs/themes/catalog.md, written by
// `go run ./cmd/gen-ts`): every entry with its axes, values, defaults, since
// versions, inherits, regions, blocks, required marks and attrs. The UI and
// the docs read the same Catalog, so they can't disagree on names.
func CatalogMD() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `go run ./cmd/gen-ts` from internal/themes/catalog.go. Do not edit. -->\n\n")
	fmt.Fprintf(&b, "# Theme catalog reference (catalog %s)\n\n", CatalogVersion)
	b.WriteString("Every name below comes from `internal/themes.Catalog`. A theme that names anything else gets a warning, never an error.\n\n")
	for _, entry := range Catalog {
		fmt.Fprintf(&b, "## `%s`\n\n", entry.Entry)
		fmt.Fprintf(&b, "- since: `%s`\n", entry.Since)
		if entry.Kind != "" {
			fmt.Fprintf(&b, "- kind: `%s`\n", entry.Kind)
		}
		if entry.Region != "" {
			fmt.Fprintf(&b, "- region: `%s`\n", entry.Region)
		}
		if entry.Required {
			b.WriteString("- required: yes (a layout that leaves it out still gets it, with a warning)\n")
		}
		if len(entry.Attrs) > 0 {
			parts := make([]string, len(entry.Attrs))
			for i, a := range entry.Attrs {
				parts[i] = "`" + a.Name + "` " + catalogAttrType(a)
			}
			fmt.Fprintf(&b, "- attrs: %s\n", strings.Join(parts, ", "))
		}
		if len(entry.Axes) == 0 {
			b.WriteString("\n")
			continue
		}
		b.WriteString("\n| axis | values | default | since | inherits |\n")
		b.WriteString("| --- | --- | --- | --- | --- |\n")
		for _, axis := range entry.Axes {
			values := make([]string, len(axis.Values))
			for i, v := range axis.Values {
				values[i] = "`" + v + "`"
			}
			inherits := "—"
			if axis.Inherits != "" {
				inherits = "`" + axis.Inherits + "`"
			}
			fmt.Fprintf(&b, "| `%s` | %s | `%s` | `%s` | %s |\n",
				axis.Name, strings.Join(values, ", "), axis.Default, axis.Since, inherits)
		}
		b.WriteString("\n")
	}
	return b.String()
}

// catalogAttrType renders one attr's type for the catalog reference.
func catalogAttrType(a types.ThemeCatalogAttr) string {
	switch a.Type {
	case "int":
		if a.Max != 0 {
			return fmt.Sprintf("(int %d..%d)", a.Min, a.Max)
		}
		return fmt.Sprintf("(int >=%d)", a.Min)
	case "enum":
		quoted := make([]string, len(a.Values))
		for i, v := range a.Values {
			quoted[i] = "`" + v + "`"
		}
		return "(enum: " + strings.Join(quoted, ", ") + ")"
	default:
		return ""
	}
}
