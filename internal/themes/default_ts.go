package themes

import (
	"encoding/json"
	"fmt"
	"strings"
)

// DefaultThemeTS renders the default theme's resolved tokens for the UI
// (apps/ui/src/gen/defaultTheme.ts, written by `go run ./cmd/gen-ts`): what
// the first paint applies when no theme is cached (issue #130). The UI reads
// it as its ThemeTokens type; TestGeneratedUpToDate fails when it is stale.
func DefaultThemeTS() string {
	raw, err := json.Marshal(Resolve(DefaultID))
	if err != nil {
		panic(fmt.Sprintf("themes: encoding default theme: %v", err))
	}
	var b strings.Builder
	b.WriteString("// Generated by `go run ./cmd/gen-ts` from internal/themes (themes.DefaultID). Do not edit.\n\n")
	b.WriteString("import type { ThemeTokens } from '../types';\n\n")
	b.WriteString("/** The default theme's resolved tokens: what the first paint applies with no cache. */\n")
	fmt.Fprintf(&b, "export const DEFAULT_THEME: ThemeTokens = %s;\n", raw)
	return b.String()
}
