// One allowlist per surface. The app page keeps the UI's list; a future
// surface starts empty and gains only the small intent list it needs.
const allowlists: Record<Surface, ReadonlySet<string>> = {
  app: new Set(APP_PAGE_METHODS),
};

/** Whether the surface may call the method. Unknown surfaces allow nothing. */
export function isMethodAllowed(surface: string, method: unknown): boolean {
  if (typeof method !== 'string') return false;
  return allowlists[surface as Surface]?.has(method) ?? false;
}

/** The refusal the bridge answers when the surface may not call the method. */
export function notAllowedMessage(method: unknown): string {
  return `refused: ${String(method)} is not allowed`;
}
